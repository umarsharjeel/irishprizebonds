		<h2>Why Prize Bonds are a common gift for children</h2>
		<p>
			Unlike cash in a card, Prize Bonds bought for a child don't get spent &mdash; the capital stays fully intact and can be cashed in at any time (after the usual 3-month rule on new bonds), while every bond is entered into the weekly draw for as long as it's held. There's no risk of loss, no tax on anything it wins &mdash; see <a href="<?php echo base_url(); ?>are-prize-bonds-worth-it/">Are Prize Bonds Worth It?</a> for how that tax-free treatment compares to a children's savings account &mdash; and no ongoing management required once it's bought.
		</p>

		<h2>How to buy for a child</h2>
		<p>
			Prize Bonds can be bought as a gift for a child through the same channels as buying for yourself &mdash; online, at any Post Office, by phone, or by Direct Debit &mdash; all detailed in our <a href="<?php echo base_url(); ?>how-to-buy-and-cash-in/">How to Buy and Cash In</a> guide. One difference: a minor (under 18) cannot register or buy online themselves, so an adult purchaser completes the purchase and registers the child as the bondholder using either the standard application form or the separate Prize Bonds Gift Application Form.
		</p>

		<h2>Documents needed</h2>
		<p>What's required depends on the amount:</p>
		<ul>
			<li><strong>€100 or less</strong> &mdash; just the name and address of the purchaser and the child receiving the gift, with only the purchaser's signature needed.</li>
			<li><strong>Over €100</strong> &mdash; proof of name, address and PPSN for both the purchaser and the child, plus the signature of both the purchaser and a nominated Parent/Guardian for the child.</li>
		</ul>

		<h2>Who controls the bond while they're a minor</h2>
		<p>
			While the bondholder is under 18, any transaction on the bond &mdash; cashing it in, changing payment details, and so on &mdash; requires the written confirmation of their nominated parent or guardian. The child doesn't gain independent access to manage or repay the bond themselves until adulthood, even though it's registered in their name from the start.
		</p>

		<h2>What happens at 18</h2>
		<p>
			On their 18th birthday, subject to providing proof of identity, the bondholder is entitled to instruct and carry out transactions on their own, without needing their parent or guardian's confirmation any longer. Full control simply transfers automatically at that point &mdash; there's no separate application to make it happen.
		</p>

		<h2>Can a child win before then?</h2>
		<p>
			Yes. A bond is entered into every draw from the moment it's bought, regardless of the holder's age, so a child's bond has exactly the same chance of winning &mdash; including the monthly &euro;500,000 jackpot &mdash; as anyone else's. If it wins while they're still a minor, the parent/guardian confirmation above simply applies to receiving or reinvesting that prize, the same as it would to cashing the bond in.
		</p>

