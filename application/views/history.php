		<h2>1956 &mdash; The legislation</h2>
		<p>
			Prize Bonds were established under the Finance (Miscellaneous Provisions) Act, 1956, introduced by then Minister
			for Finance Gerard Sweetman. It was one of the first major pieces of financial legislation of its era, creating
			a new kind of state savings product: instead of paying interest, holders would be entered into regular draws
			for tax-free cash prizes.
		</p>

		<h2>1957 &mdash; Bonds go on sale</h2>
		<p>
			Prize Bonds were first sold in March 1957, with the first draw following later that year. Under the original
			rules, the draw had to be held at the Bank of Ireland's headquarters on College Green in Dublin &mdash; because
			the Bank of Ireland, as the government's banker at the time, was the operator of the scheme on behalf of the
			Minister for Finance.
		</p>

		<h2>1989 &mdash; A new operator</h2>
		<p>
			After more than three decades under the Bank of Ireland's administration, the Minister for Finance awarded the
			contract to run the Prize Bond scheme to the newly formed <strong>Prize Bond Company Limited</strong> in 1989.
			This separated day-to-day running of the scheme from the state's banking arrangements, setting up the
			structure that, with the addition of the NTMA a year later, still underpins Prize Bonds today.
		</p>

		<h2>A consistent thread: tax-free from day one</h2>
		<p>
			Through every operational change &mdash; Bank of Ireland, then the Prize Bond Company, then the NTMA's
			oversight &mdash; one feature of Prize Bonds has stayed constant since 1957: prizes have always been paid
			out tax-free, with no DIRT, Income Tax, PRSI, or Capital Gains Tax due on winnings. That's been a defining
			part of the product's appeal for close to seven decades, long before "tax-free savings" became a common
			marketing phrase for other products.
		</p>

		<h2>1990 &mdash; The NTMA takes over</h2>
		<p>
			The National Treasury Management Agency (NTMA) was established in 1990 and took over overall responsibility
			for the Prize Bond scheme, a role it still holds today. Day-to-day administration &mdash; sales, prize payments,
			and customer service &mdash; is handled by An Post through Ireland State Savings.
		</p>

		<h2>Today</h2>
		<p>
			Nearly 70 years after the first bonds went on sale, Prize Bonds remain one of Ireland's most recognisable
